#!/usr/bin/env python3
"""
Copy the reference material the web app needs into web/data as plain scripts.

The web app opens from file://, where a page cannot fetch() files next to it, so
data ships as <script> files that assign to a global instead. Run this after
editing anything under reference/ that the app uses:

    python3 tools/build_web.py

Only shareable material goes in: the factory block tier and the guides. The
user tier stays on each person's machine; the app reads it off their own pedal.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "reference"
OUT = ROOT / "web" / "data"

GUIDES = {
    "choosingBlocks": "choosing-blocks.md",
    "whatBlocksModel": "what-blocks-model.md",
    "presetFormat": "preset-format.md",
}
EXAMPLES = ("13.json", "41.json", "1.json", "2.json")


def script(name: str, value) -> str:
    body = json.dumps(value, ensure_ascii=False, separators=(",", ":"))
    return f"// Generated by tools/build_web.py - do not edit.\n(globalThis.AT_DATA = globalThis.AT_DATA || {{}}).{name} = {body};\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    factory = json.loads((REF / "blocks-factory.json").read_text())
    (OUT / "blocks-factory.js").write_text(script("blocksFactory", factory))
    knowledge = {key: (REF / name).read_text() for key, name in GUIDES.items()}
    knowledge["examples"] = {name: json.loads((REF / "examples" / name).read_text()) for name in EXAMPLES}
    (OUT / "knowledge.js").write_text(script("knowledge", knowledge))
    print(f"wrote {OUT.relative_to(ROOT)}/blocks-factory.js ({len(factory['blocks'])} blocks) and knowledge.js")


if __name__ == "__main__":
    main()
